-- Property Tax Management: core schema (nine tables). Demo system, fictional data.
-- Money is NUMERIC(14,2); tax rates NUMERIC(10,8). Foreign keys default to NO ACTION
-- so financial history can never be cascade-deleted.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(255) NOT NULL UNIQUE CHECK (email = lower(email)),
    full_name   VARCHAR(150) NOT NULL,
    role        VARCHAR(20)  NOT NULL CHECK (role IN ('RESIDENT', 'TAX_OFFICER', 'ADMIN')),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- An owner may (optionally) have one resident login: 1:1 users <-> owners.
CREATE TABLE owners (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT UNIQUE REFERENCES users (id),
    full_name        VARCHAR(150) NOT NULL,
    email            VARCHAR(255),
    phone            VARCHAR(30),
    mailing_address  VARCHAR(255),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE properties (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roll_number     VARCHAR(20)  NOT NULL UNIQUE,
    street_address  VARCHAR(255) NOT NULL,
    city            VARCHAR(100) NOT NULL,
    postal_code     VARCHAR(7)   NOT NULL CHECK (postal_code ~ '^[A-Z][0-9][A-Z] [0-9][A-Z][0-9]$'),
    property_class  VARCHAR(20)  NOT NULL CHECK (property_class IN ('RESIDENTIAL', 'COMMERCIAL', 'INDUSTRIAL')),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Many-to-many properties <-> owners, with ownership share as payload.
CREATE TABLE property_owners (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id        BIGINT       NOT NULL REFERENCES properties (id),
    owner_id           BIGINT       NOT NULL REFERENCES owners (id),
    ownership_percent  NUMERIC(5,2) NOT NULL CHECK (ownership_percent > 0 AND ownership_percent <= 100),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (property_id, owner_id)
);
CREATE INDEX idx_property_owners_owner ON property_owners (owner_id);

CREATE TABLE assessments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id      BIGINT        NOT NULL REFERENCES properties (id),
    tax_year         SMALLINT      NOT NULL CHECK (tax_year BETWEEN 2000 AND 2100),
    assessed_value   NUMERIC(14,2) NOT NULL CHECK (assessed_value >= 0),
    assessment_date  DATE          NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (property_id, tax_year)
);

-- One rate per (year, property class). Fictional demo rates.
CREATE TABLE tax_rates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_year        SMALLINT      NOT NULL CHECK (tax_year BETWEEN 2000 AND 2100),
    property_class  VARCHAR(20)   NOT NULL CHECK (property_class IN ('RESIDENTIAL', 'COMMERCIAL', 'INDUSTRIAL')),
    rate            NUMERIC(10,8) NOT NULL CHECK (rate > 0 AND rate < 1),
    description     VARCHAR(255),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (tax_year, property_class)
);

-- 1:1 with property. Outstanding balance is derived (bills - payments), never stored.
CREATE TABLE tax_accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number  VARCHAR(20) NOT NULL UNIQUE,
    property_id     BIGINT      NOT NULL UNIQUE REFERENCES properties (id),
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLOSED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- assessment_id / tax_rate_id record exactly which inputs produced the amount.
CREATE TABLE tax_bills (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_number     VARCHAR(30)   NOT NULL UNIQUE,
    tax_account_id  BIGINT        NOT NULL REFERENCES tax_accounts (id),
    assessment_id   BIGINT        NOT NULL REFERENCES assessments (id),
    tax_rate_id     BIGINT        NOT NULL REFERENCES tax_rates (id),
    tax_year        SMALLINT      NOT NULL CHECK (tax_year BETWEEN 2000 AND 2100),
    bill_type       VARCHAR(10)   NOT NULL CHECK (bill_type IN ('INTERIM', 'FINAL')),
    amount          NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    issue_date      DATE          NOT NULL,
    due_date        DATE          NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'ISSUED'
                    CHECK (status IN ('ISSUED', 'PARTIALLY_PAID', 'PAID', 'CANCELLED')),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CHECK (due_date >= issue_date)
);
-- At most one live interim and one live final bill per account per year; cancelled bills may be reissued.
CREATE UNIQUE INDEX uq_tax_bills_live ON tax_bills (tax_account_id, tax_year, bill_type)
    WHERE status <> 'CANCELLED';

-- Simulated payment records only. reference_number blocks duplicate recording.
CREATE TABLE payments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_bill_id       BIGINT        NOT NULL REFERENCES tax_bills (id),
    amount            NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    payment_date      DATE          NOT NULL,
    method            VARCHAR(20)   NOT NULL CHECK (method IN ('CHEQUE', 'BANK_TRANSFER', 'PRE_AUTHORIZED', 'COUNTER')),
    reference_number  VARCHAR(50)   NOT NULL UNIQUE,
    status            VARCHAR(10)   NOT NULL DEFAULT 'RECORDED' CHECK (status IN ('RECORDED', 'REVERSED')),
    recorded_by       BIGINT        NOT NULL REFERENCES users (id),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_payments_tax_bill ON payments (tax_bill_id);
